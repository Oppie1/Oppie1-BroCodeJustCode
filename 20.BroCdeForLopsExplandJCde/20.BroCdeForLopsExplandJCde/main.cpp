#include <iostream>
using namespace std;



int main() {

	
	for (int index = 1; index < 9; index += 2) {

		cout << index << " Happy New Year" << endl;
	}

	cout << endl;
	
	for (int i = 1; i < 4; i++) {

		cout << i << " Happy New Year" << endl;
	}

	cout << endl;

	for (int i = 1; i <= 5; i++) {

		cout << i << " Happy New Year" << endl;

	}

	cout << "\n";

	for (int i = 1; i < 11; i++) {

		cout << i;
	}

	cout <<"\n" << "Happy New Year" << endl;

	cout << endl;

	for (int i = 1; i <= 10; i += 2) {

		cout << i;
	}

	cout << " Happy New Year" << endl;

	cout << endl;

	for (int i = 0; i <= 10; i += 3) {

		cout << i << endl;
	}

	cout << " Happy New Year" << endl;

	cout << endl;

	for (int i = 9; i > 0; i--) {

		cout << i;
	}

	cout << " Happy New Year" << endl;

	cout << endl;

	for (int i = 11; i > 0; i -= 2) {

		cout << " " << i << endl;
	}

	cout << " Happy New Year" << endl;


}